'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const { createHash } = require('node:crypto');
const root = path.resolve(__dirname, '..');
const target = path.join(root, 'src/modules/products/domain/services/admin-media-registry.generated.ts');
const files = execFileSync('git', ['ls-files', '-z', 'frontend/public'], { cwd: root, encoding: 'utf8' }).split('\0')
  .filter(file => /\.(?:png|jpe?g|webp|gif|avif|svg)$/i.test(file)).sort();
const resources = files.map(file => {
  const absolute = path.join(root, file);
  if (!fs.lstatSync(absolute).isFile()) throw new Error(`Media must be a regular tracked file: ${file}`);
  return { assetPath: file.slice('frontend/public'.length), sha256: createHash('sha256').update(fs.readFileSync(absolute)).digest('hex') };
});
const output = '// Generated by scripts/generate-admin-media-registry.js from tracked frontend/public images. Do not edit.\n'
  + 'export const ADMIN_MEDIA_RESOURCES = ' + JSON.stringify(resources, null, 2) + ' as const;\n';
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) throw new Error('Admin media registry drift; regenerate from tracked files');
} else fs.writeFileSync(target, output);
